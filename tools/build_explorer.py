#!/usr/bin/env python3
"""Build the attack explorer's data file (ai-triage/data.js on the portfolio site).

The explorer page shows every recorded model answer. This script turns the
evaluation results in results/*.json into the compact data file the page reads.

The dataset part (the canary, the 8 payloads, the 27 alerts and the 136 attack
variants) is taken from an existing data.js with --base, so the alert text the
page shows never changes when a model is added. Every model's summary and
answers are rebuilt from its results file.

Usage, from the repo root:
    python tools/build_explorer.py --base ../AhmedDAH1.github.io/ai-triage/data.js \
        --out ../AhmedDAH1.github.io/ai-triage/data.js

Check mode (exit 1 if the output would differ from --out):
    python tools/build_explorer.py --base ... --out ... --check
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HEADER = "// Generated by tools/build_explorer.py from github.com/AhmedDAH1/ai-alert-triage/results\n"
PREFIX = "window.TRIAGE = "
MODES = ("naive", "hardened", "guarded", "strict")

# key used by the page, results file, label, note. Order is the order on the page.
MODELS = [
    ("qwen", "results/qwen2.5-7b.json", "Qwen 2.5 7B", "small model, runs on a laptop"),
    ("deepseek", "results/deepseek-v4.1-flash-1017.json", "DeepSeek V4.1 Flash", "large cloud model, via a reseller"),
    ("pro", "results/deepseek-v4-pro.json", "DeepSeek V4 Pro", "largest cloud model, via a reseller"),
]

# The summary keeps only the numbers the page uses.
ATTACK_KEYS = ("variants", "dismissed", "downgraded", "obeyed", "model_flagged")


def load_data_js(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    start = text.index(PREFIX) + len(PREFIX)
    return json.loads(text[start:].rstrip().rstrip(";"))


def compact_answer(d: dict) -> dict:
    return {
        "v": d["verdict"],
        "s": d["severity"],
        "c": d["confidence"],
        "r": d["reasoning"],
        "n": d["next_steps"],
        "i": d["model_flagged_injection"],
        "e": d["evidence"],
        "o": d["overrides"],
    }


def build_model(results: dict, alert_ids: list[str], variant_ids: list[str], label: str, note: str) -> dict:
    summary, answers = {}, {}
    for mode in MODES:
        m = results["modes"][mode]
        summary[mode] = {"clean": m["clean"], "attack": {k: m["attack"][k] for k in ATTACK_KEYS}}
    for key, part in [(a, "clean") for a in alert_ids] + [(v, "attack") for v in variant_ids]:
        answers[key] = {}
        for mode in MODES:
            details = results["modes"][mode]["details"][part]
            if key not in details:
                sys.exit(f"{results['model']}: no {mode} answer for {key}; was it run on the same dataset?")
            answers[key][mode] = compact_answer(details[key])
    return {"name": results["model"], "label": label, "note": note, "summary": summary, "answers": answers}


def build(base: dict, root: Path) -> str:
    alert_ids = [a["id"] for a in base["alerts"]]
    variant_ids = list(base["variants"])
    models = {}
    for key, file, label, note in MODELS:
        results = json.loads((root / file).read_text(encoding="utf-8"))
        models[key] = build_model(results, alert_ids, variant_ids, label, note)
    data = {"canary": base["canary"], "payloads": base["payloads"], "models": models,
            "alerts": base["alerts"], "variants": base["variants"]}
    return HEADER + PREFIX + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--base", type=Path, required=True, help="existing data.js to take the dataset from")
    p.add_argument("--out", type=Path, required=True, help="where to write the new data.js")
    p.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent, help="repo root (default: this repo)")
    p.add_argument("--check", action="store_true", help="only report whether --out is up to date")
    args = p.parse_args()

    text = build(load_data_js(args.base), args.root)
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        print("up to date" if current == text else "out of date")
        sys.exit(0 if current == text else 1)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(text) // 1024} KB, models: {', '.join(k for k, *_ in MODELS)})")


if __name__ == "__main__":
    main()
